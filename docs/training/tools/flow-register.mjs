// Daftar akun Pembeli baru. node flow-register.mjs m|d  -> tulis tools/.accounts.json {m:{email},d:{email}}
import fs from "node:fs/promises";
import { launch, ctx, BASE, ROOT, PASSWORD } from "./pb-lib.mjs";
const vk = process.argv[2] ?? "m";
const OUT = `${ROOT}/shots/pengunjung`; await fs.mkdir(OUT, { recursive: true });
const b = await launch(); const c = await ctx(b, vk); const p = await c.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(String(e.message).slice(0, 150)));
p.on("response", (r) => { if (r.status() >= 400 && /\/api\//.test(r.url())) errs.push(`${r.status()} ${r.request().method()} ${new URL(r.url()).pathname}`); });
const snap = async (n) => { await p.waitForTimeout(700); await p.screenshot({ path: `${OUT}/${n}-${vk}.png` }); console.log("shot", n, vk); };
const email = `warga.contoh.${Date.now().toString(36)}@kucur.example`;
await p.goto(`${BASE}/register`); await p.locator("form.register-form").waitFor();
await snap("09-daftar-data-diri");
await p.locator("input[name=fullName]").fill("Siti Aminah");
await p.locator("input[name=email]").fill(email);
await p.locator("input[name=phone]").fill("081234567890");
await p.locator("input[name=password]").fill(PASSWORD);
await p.locator("input[name=confirmPassword]").fill(PASSWORD);
await p.getByLabel("Nama penerima").fill("Siti Aminah");
await p.getByLabel(/Nomor WhatsApp penerima/).fill("081234567890");
await p.getByLabel(/Label alamat/).fill("Rumah");
await p.getByLabel(/Alamat lengkap dan patokan/).fill("Dusun Kucur RT 02 RW 01, dekat balai desa, Kecamatan Dau, Kabupaten Malang");
await p.getByRole("button", { name: /Gunakan Lokasi Saya/ }).click();
await p.waitForTimeout(2500);
await p.getByLabel(/Alamat lengkap dan patokan/).scrollIntoViewIfNeeded();
await p.getByRole("button", { name: /Gunakan Lokasi Saya/ }).scrollIntoViewIfNeeded();
await snap("10-daftar-alamat-peta");
console.log("lat/lng:", await p.locator("input[type=number]").evaluateAll((l) => l.map((i) => i.value)));
await p.getByRole("checkbox").check();
await p.getByRole("button", { name: /Buat Akun Pembeli/ }).scrollIntoViewIfNeeded();
await snap("11-daftar-setuju");
await p.getByRole("button", { name: /Buat Akun Pembeli/ }).click();
await p.waitForTimeout(3500);
console.log("url sesudah daftar:", p.url().replace(BASE, ""));
await snap("12-daftar-berhasil");
const acc = JSON.parse(await fs.readFile(`${ROOT}/tools/.accounts.json`, "utf8").catch(() => "{}")); acc[vk] = { email }; await fs.writeFile(`${ROOT}/tools/.accounts.json`, JSON.stringify(acc));
console.log("email", email, "errors", errs);
await b.close();
